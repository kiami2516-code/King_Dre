num_1 = float(input("Digite o primeiro número : "))
num_2 = float(input("Digite o segundo número : "))

operacao = input("Que operação que deseja utilizar ? (+ - / *)")

if operacao == "+":
    resultado = num_1+num_2
    print(f"O resultado da soma é {resultado}")

elif operacao == "-":
    resultado = num_1-num_2
    print(f"O resultado da subtraçaõ é {resultado}")

elif operacao == "/":
        resultado = num_1/num_2
        print(f"O resultado dessa divisão é {resultado}")

elif operacao == "*":
    resultado = num_1*num_2
    print(f"o resultado é esse {resultado} pau no cu")


